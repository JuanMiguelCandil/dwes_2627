<?php

/*
    Declaración de funciones matemáticas:
    - Sumar: recibe dos números enteros y devuelve su suma.
    - Restar: recibe dos números enteros y devuelve su resta.
    - Multipliación: recibe dos números enteros y devuelve su multiplicación.
*/

function sumar(int $a, int $b) {
    return $a + $b;
}

function restar(int $a, int $b) {
    return $a - $b;
}

function multiplicar(int $a, int $b) {
    return $a * $b;
}